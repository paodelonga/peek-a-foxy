def run_real(command: list[str], cwd: Path | None = None, env: dict[str, str] | None = None) -> int:
    done = subprocess.run(command, cwd=cwd, env=env, capture_output=True, timeout=120, check=False)
    return done.returncode


def run_script(script: str) -> int:
    """Run a script as the elevated process would, for scripts the generator would not make."""
    powershell = elevate.powershell_path(elevate.system_directory())
    return run_real([powershell, *elevate.POWERSHELL_FLAGS, elevate.encoded_command(script)])


def run_folder(folder: Path, payloads: list[bytes] | None = None) -> int:
    return run_real(elevate.helper_command(folder, payloads or [CONFIG, PREFS]))


@pytest.fixture
def junction():
    """Make directory junctions with mklink /J (no privilege needed) and remove them afterwards."""
    made: list[Path] = []

    def make(link: Path, target: Path) -> Path:
        command = ["cmd", "/c", "mklink", "/J", str(link), str(target)]
        subprocess.run(command, check=True, capture_output=True)
        made.append(link)
        return link

    yield make
    for link in reversed(made):
        if os.path.lexists(link):
            os.rmdir(link)  # removes the junction, not what it points to


