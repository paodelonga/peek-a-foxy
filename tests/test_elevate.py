# --- reading the generated script the way PowerShell's tokenizer does ---------------------------


def split_literals(script: str) -> tuple[str, list[str]]:
    """The script with every single-quoted literal emptied, and the literals' values in order.

    PowerShell opens and closes such a literal with any of the five single-quote characters, and
    two of them in a row inside it stand for one (the second). The template has no comment and no
    double-quoted string, so this is all the tokenizing that matters here.
    """
    code: list[str] = []
    literals: list[str] = []
    i = 0
    while i < len(script):
        if script[i] not in elevate.SINGLE_QUOTES:
            code.append(script[i])
            i += 1
            continue
        value: list[str] = []
        j = i + 1
        while True:
            assert j < len(script), "a literal is not closed"
            if script[j] in elevate.SINGLE_QUOTES:
                if j + 1 < len(script) and script[j + 1] in elevate.SINGLE_QUOTES:
                    value.append(script[j + 1])
                    j += 2
                    continue
                break
            value.append(script[j])
            j += 1
        literals.append("".join(value))
        code.append("''")
        i = j + 1
    return "".join(code), literals


REFERENCE_FOLDER = "C:\\Program Files\\Mozilla Firefox"


def reference(payloads: list[bytes]) -> tuple[str, list[str]]:
    return split_literals(elevate.helper_script(REFERENCE_FOLDER, payloads))


def folder_index() -> int:
    """Where the folder is among the literals ('Stop' of $ErrorActionPreference comes first)."""
    return reference([CONFIG, PREFS])[1].index(REFERENCE_FOLDER)


def folder_literal(script: str) -> str:
    return split_literals(script)[1][folder_index()]


def assert_only_data_changed(folder: str, payloads: list[bytes]) -> None:
    """The script for ``folder`` is the reference script with only the folder literal changed."""
    code, literals = split_literals(elevate.helper_script(folder, payloads))
    expected_code, expected_literals = reference(payloads)
    assert code == expected_code  # not a single character of code came from the folder name
    index = folder_index()
    assert literals[index] == folder  # and PowerShell reads back exactly the folder
    assert literals[:index] + literals[index + 1 :] == (
        expected_literals[:index] + expected_literals[index + 1 :]
    )


def decoded(command: list[str]) -> str:
    return base64.b64decode(command[-1], validate=True).decode("utf-16-le", "surrogatepass")


# --- the command: System32 PowerShell and an encoded script --------------------------------------


def test_the_command_is_the_system_powershell_with_the_encoded_script(pinned, tmp_path):
    command = elevate.helper_command(tmp_path, [CONFIG, PREFS])
    system = elevate.system_directory()
    assert command[0] == system + "\\WindowsPowerShell\\v1.0\\powershell.exe"
    assert command[1:4] == ["-NoProfile", "-NonInteractive", "-EncodedCommand"]
    assert len(command) == 5  # nothing else: no payload, no path on the command line itself
    assert decoded(command) == elevate.helper_script(str(tmp_path), [CONFIG, PREFS])
    raw = base64.b64decode(command[-1])
    assert raw[:2] == b"S\x00" and not raw.startswith(b"\xff\xfe")  # UTF-16LE, no byte order mark


def test_the_encoded_command_round_trips_any_text():
    for text in ["", "a", "é 🦊 \u202e", "x" * 1001, "\udc80 lone surrogate"]:
        data = base64.b64decode(elevate.encoded_command(text))
        assert data.decode("utf-16-le", "surrogatepass") == text


