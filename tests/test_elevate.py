def test_the_payloads_and_pins_are_literals_and_appear_nowhere_else(pinned):
    script = elevate.helper_script(REFERENCE_FOLDER, [CONFIG, PREFS])
    code, literals = split_literals(script)
    encoded = [base64.b64encode(data).decode("ascii") for data in (CONFIG, PREFS)]
    pins = list(elevate.PINNED_SHA256.values())
    index = folder_index()
    assert literals[index : index + 5] == [REFERENCE_FOLDER, *encoded, *pins]
    for value in [*encoded, *pins]:
        assert script.count(value) == 1 and value not in code
    assert "@@" not in script


